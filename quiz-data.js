function quizStreak(s) {
  const d = new Date();
  if (!s.days[quizDate(d)]) d.setDate(d.getDate() - 1);
  let n = 0;
  while (s.days[quizDate(d)]) { n++; d.setDate(d.getDate() - 1); }
  return n;
}

